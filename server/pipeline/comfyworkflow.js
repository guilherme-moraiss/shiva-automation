/**
 * Bring any ComfyUI workflow into the pipeline:
 *   1. uiToApi()      — convert the UI/graph format (what the editor saves and what Comfy Cloud share links return)
 *                        into the API format that /prompt accepts. Uses `widgets_values_named` when the frontend
 *                        saved it, otherwise maps `widgets_values` positionally with /object_info.
 *   2. suggestMapping() — guess which node inputs the app should fill (images, source video, prompt, seed…).
 *   3. applyMapping()   — at run time, write the pipeline's values into those inputs.
 */

const SKIP_TYPES = new Set(['Note', 'MarkdownNote', 'PrimitiveNode', 'Reroute', 'GroupNode', 'Label (rgthree)', 'Fast Groups Bypasser (rgthree)']);
const WIDGET_TYPES = new Set(['INT', 'FLOAT', 'STRING', 'BOOLEAN', 'COMBO']);

